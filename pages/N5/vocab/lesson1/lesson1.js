function shuffleLesson1Array(array) {
  const newArray = [...array];

  for (let i = newArray.length - 1; i > 0; i--) {
    const randomIndex = Math.floor(
      Math.random() * (i + 1)
    );

    [newArray[i], newArray[randomIndex]] = [
      newArray[randomIndex],
      newArray[i]
    ];
  }

  return newArray;
}
function createLesson1PracticeAnswers(
  correctWord,
  answerType
) {
  const correctAnswer =
    answerType === "meaning"
      ? correctWord.meaning
      : correctWord.kana;

  const wrongAnswers = allFlashcardData
    .filter(word => {
      return word.kana !== correctWord.kana;
    })
    .map(word => {
      return answerType === "meaning"
        ? word.meaning
        : word.kana;
    })
    .filter((answer, index, array) => {
      return (
        answer &&
        answer !== correctAnswer &&
        array.indexOf(answer) === index
      );
    });

  const selectedWrongAnswers =
    shuffleLesson1Array(wrongAnswers).slice(0, 3);

  return shuffleLesson1Array([
    correctAnswer,
    ...selectedWrongAnswers
  ]);
}
function createLesson1PracticeQuestions(
  practiceNumber
) {
  const words = lesson1PracticeWords[practiceNumber];

  if (!words || words.length < 10) {
    return [];
  }

  const questions = [];
  words.slice(0, 8).forEach(word => {
    questions.push({
      type: "kanaToMeaning",
      question: word.kana,
      correct: word.meaning,
      answers: createLesson1PracticeAnswers(
        word,
        "meaning"
      ),
      word: word
    });
  });
    words.slice(2, 10).forEach(word => {
    questions.push({
      type: "meaningToKana",
      question: word.meaning,
      correct: word.kana,
      answers: createLesson1PracticeAnswers(
        word,
        "kana"
      ),
      word: word
    });
  });
 const audioWords =
    shuffleLesson1Array(words).slice(0, 4);

  audioWords.forEach(word => {
    questions.push({
      type: "audioToMeaning",
      question: "",
      correct: word.meaning,
      answers: createLesson1PracticeAnswers(
        word,
        "meaning"
      ),
      word: word
    });
  });
    return shuffleLesson1Array(questions);
}
function togglePractice(practiceNumber, button) {
  if (!button) {
    const btns = document.querySelectorAll(".practice-title-btn");
    button = btns[Number(practiceNumber) - 1] || btns[0];
  }

  if (!button) return;

  const practiceItem = button.closest(".practice-item");
  if (!practiceItem) return;

  const panel = practiceItem.querySelector(".practice-panel");
  if (!panel) return;

  const isOpen = panel.classList.contains("open");

  lesson1PracticeAudio.pause();
  lesson1PracticeAudio.currentTime = 0;

  document.querySelectorAll(".practice-panel").forEach(item => {
    item.classList.remove("open");
    item.innerHTML = "";
  });

  document.querySelectorAll(".practice-title-btn").forEach((practiceButton, index) => {
    practiceButton.classList.remove("active");
    practiceButton.textContent = `📝 Luyện tập ${index + 1}`;
  });

  if (isOpen) {
    currentPracticePanel = null;
    currentPracticeNumber = null;
    return;
  }

  currentPracticeNumber = Number(practiceNumber);
  currentPracticePanel = panel;

  button.classList.add("active");
  button.textContent = `▼ Luyện tập ${currentPracticeNumber}`;

  panel.classList.add("open");

 startLesson1Practice();
}

