function closeLesson1Practice() {
  lesson1PracticeAudio.pause();
  lesson1PracticeAudio.currentTime = 0;

  if (!currentPracticePanel) {
    return;
  }

  const practiceItem =
    currentPracticePanel.closest(".practice-item");

  const button =
    practiceItem.querySelector(
      ".practice-title-btn"
    );

  currentPracticePanel.classList.remove("open");
  currentPracticePanel.innerHTML = "";

  button.classList.remove("active");
  button.textContent =
    `▶ Luyện tập ${currentPracticeNumber}`;

  currentPracticePanel = null;
  currentPracticeNumber = null;
}
function playLesson1PracticeQuestionAudio(
  button = null
) {
  const question =
    currentPracticeQuestions[
      currentPracticeQuestionIndex
    ];

  if (!question || !question.word) {
    return;
  }

  const romaji = question.word.romaji;

  if (!romaji) {
    console.log(
      "Từ này chưa có dữ liệu romaji."
    );

    return;
  }

  lesson1PracticeAudio.pause();
  lesson1PracticeAudio.currentTime = 0;

  lesson1PracticeAudio.src =
    `../../../../assets/n5_vocab_audio/lesson1/${romaji}.mp3`;


  if (button) {
    button.classList.add("playing");
  }


  lesson1PracticeAudio
    .play()
    .catch(error => {
      console.log(
        "Không phát được âm thanh:",
        romaji,
        error
      );

      if (button) {
        button.classList.remove("playing");
      }
    });


  lesson1PracticeAudio.onended = () => {
    if (button) {
      button.classList.remove("playing");
    }
  };

  lesson1PracticeAudio.onerror = () => {
    if (button) {
      button.classList.remove("playing");
    }

    console.log(
      `Không tìm thấy file: ${romaji}.mp3`
    );
  };
}

