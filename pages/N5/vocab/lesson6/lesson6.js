function shuffleLesson6Array(array) {
  const newArray = [...array];

  for (let i = newArray.length - 1; i > 0; i--) {
    const randomIndex = Math.floor(
      Math.random() * (i + 1)
    );

    [newArray[i], newArray[randomIndex]] = [
      newArray[randomIndex],
      newArray[i]
    ];
  }

  return newArray;
}
function createLesson6PracticeAnswers(
  correctWord,
  answerType
) {
  const correctAnswer =
    answerType === "meaning"
      ? correctWord.meaning
      : correctWord.kana;

  const wrongAnswers = allFlashcardData
    .filter(word => {
      return word.kana !== correctWord.kana;
    })
    .map(word => {
      return answerType === "meaning"
        ? word.meaning
        : word.kana;
    })
    .filter((answer, index, array) => {
      return (
        answer &&
        answer !== correctAnswer &&
        array.indexOf(answer) === index
      );
    });

  const selectedWrongAnswers =
    shuffleLesson6Array(wrongAnswers).slice(0, 3);

  return shuffleLesson6Array([
    correctAnswer,
    ...selectedWrongAnswers
  ]);
}
function createLesson6PracticeQuestions(practiceNumber) {
  const words = lesson6PracticeWords[practiceNumber];

  if (!words || words.length === 0) {
    return [];
  }

  const questions = [];

  const shuffledWords = shuffleLesson6Array([
    ...words
  ]);

  const kanaWords = shuffledWords.slice(
    0,
    Math.min(8, shuffledWords.length)
  );

  const meaningWords = shuffleLesson6Array([
    ...words
  ]).slice(
    0,
    Math.min(8, words.length)
  );

  const audioWords = shuffleLesson6Array([
    ...words
  ]).slice(
    0,
    Math.min(4, words.length)
  );

  kanaWords.forEach(word => {
    questions.push({
      type: "kanaToMeaning",
      question: word.kana,
      correct: word.meaning,
      answers: createLesson6PracticeAnswers(
        word,
        "meaning"
      ),
      word: word
    });
  });

  meaningWords.forEach(word => {
    questions.push({
      type: "meaningToKana",
      question: word.meaning,
      correct: word.kana,
      answers: createLesson6PracticeAnswers(
        word,
        "kana"
      ),
      word: word
    });
  });

  audioWords.forEach(word => {
    questions.push({
      type: "audioToMeaning",
      question: "",
      correct: word.meaning,
      answers: createLesson6PracticeAnswers(
        word,
        "meaning"
      ),
      word: word
    });
  });

  return shuffleLesson6Array(questions);
}
function togglePractice(practiceNumber, button) {
  if (!button) {
    const btns = document.querySelectorAll(".practice-title-btn");
    button = btns[Number(practiceNumber) - 1] || btns[0];
  }

  if (!button) return;

  const practiceItem = button.closest(".practice-item");
  if (!practiceItem) return;

  const panel = practiceItem.querySelector(".practice-panel");
  if (!panel) return;

  const isOpen = panel.classList.contains("open");

  lesson6PracticeAudio.pause();
  lesson6PracticeAudio.currentTime = 0;

  document.querySelectorAll(".practice-panel").forEach(item => {
    item.classList.remove("open");
    item.innerHTML = "";
  });

  document.querySelectorAll(".practice-title-btn").forEach((practiceButton, index) => {
    practiceButton.classList.remove("active");
    practiceButton.textContent = `📝 Luyện tập ${index + 1}`;
  });

  if (isOpen) {
    currentPracticePanel = null;
    currentPracticeNumber = null;
    return;
  }

  currentPracticeNumber = Number(practiceNumber);
  currentPracticePanel = panel;

  button.classList.add("active");
  button.textContent = `▼ Luyện tập ${currentPracticeNumber}`;

  panel.classList.add("open");

  startLesson6Practice();
}

function startLesson6Practice() {
  currentPracticeQuestions =
    createLesson6PracticeQuestions(
      currentPracticeNumber
    );

  currentPracticeQuestionIndex = 0;
  currentPracticeScore = 0;
  lesson6AnswerLocked = false;

  showLesson6PracticeQuestion();
}
function showLesson6PracticeQuestion() {
  const question =
    currentPracticeQuestions[
      currentPracticeQuestionIndex
    ];

  if (!question) {
    showLesson6PracticeResult();
    return;
  }

  lesson6AnswerLocked = false;

  lesson6PracticeAudio.pause();
  lesson6PracticeAudio.currentTime = 0;

  const totalQuestions =
    currentPracticeQuestions.length;

  const questionNumber =
    currentPracticeQuestionIndex + 1;

  const progressPercent =
    (questionNumber / totalQuestions) * 100;


  let instruction = "";

  if (question.type === "kanaToMeaning") {
    instruction =
      "Chọn đáp án đúng";
  }

  if (question.type === "meaningToKana") {
    instruction =
      "Chọn đáp án đúng";
  }

  if (question.type === "audioToMeaning") {
    instruction =
      "Chọn đáp án đúng";
  }


  let questionHTML = `
    <div class="practice-question-text">
      ${question.question}
    </div>
  `;


  if (question.type === "audioToMeaning") {
    questionHTML = `
      <div class="practice-audio-area">

        <button
          class="practice-audio-btn"
          onclick="playLesson6PracticeQuestionAudio(this)"
        >
          <span class="practice-speaker">
            🔊
          </span>
        </button>

      </div>
    `;
  }


  const answersHTML = question.answers
    .map((answer, index) => {
      return `
        <button
          class="practice-answer-btn"
          data-answer="${encodeURIComponent(answer)}"
          onclick="checkLesson6PracticeAnswer(this)"
        >

          <span class="answer-letter">
            ${String.fromCharCode(65 + index)}
          </span>

          <span class="answer-text">
            ${answer}
          </span>

        </button>
      `;
    })
    .join("");


  currentPracticePanel.innerHTML = `
    <div class="practice-box">

      <div class="practice-box-title">
        Từ vựng bài 6
      </div>

      <div class="practice-progress-info">

        <span>
          Câu ${questionNumber}/${totalQuestions}
        </span>

        <span>
          Điểm: ${currentPracticeScore}
        </span>

      </div>

      <div class="practice-progress-track">

        <div
          class="practice-progress-fill"
          style="width: ${progressPercent}%"
        >
        </div>

      </div>

      <div class="practice-content">

        <div class="practice-instruction">
          ${instruction}
        </div>

        ${questionHTML}

        <div class="practice-answer-list">
          ${answersHTML}
        </div>

        <div
          id="practiceFeedback"
          class="practice-feedback"
        >
        </div>

        <div
          id="practiceNextArea"
          class="practice-next-area"
        >
        </div>

      </div>

    </div>
  `;
   if (question.type === "audioToMeaning") {
    setTimeout(() => {
      playLesson6PracticeQuestionAudio();
    }, 500);
  }
}
function checkLesson6PracticeAnswer(button) {
  if (lesson6AnswerLocked) {
    return;
  }

  lesson6AnswerLocked = true;

  const question =
    currentPracticeQuestions[
      currentPracticeQuestionIndex
    ];

  const selectedAnswer = decodeURIComponent(
    button.dataset.answer
  );

  const answerButtons =
    currentPracticePanel.querySelectorAll(
      ".practice-answer-btn"
    );


  answerButtons.forEach(answerButton => {
    answerButton.disabled = true;

    const answer = decodeURIComponent(
      answerButton.dataset.answer
    );

    if (answer === question.correct) {
      answerButton.classList.add("correct");
    }
  });


  const feedback =
    currentPracticePanel.querySelector(
      "#practiceFeedback"
    );


  if (selectedAnswer === question.correct) {
    currentPracticeScore++;

    button.classList.add("correct");

    feedback.innerHTML = `
      <div class="feedback-correct">
        😊🎉
      </div>
    `;
  } else {
    button.classList.add("wrong");

    feedback.innerHTML = `
      <div class="feedback-wrong">
       😢
      </div>
    `;
  }


  const nextArea =
    currentPracticePanel.querySelector(
      "#practiceNextArea"
    );

  const isLastQuestion =
  currentPracticeQuestionIndex ===
  currentPracticeQuestions.length - 1;

if (isLastQuestion) {

  // Hiện kết quả sau 1 giây
  setTimeout(() => {
    showLesson6PracticeResult();
  }, 1000);

} else {

  nextArea.innerHTML = `
    <button
      class="practice-next-btn"
      onclick="nextLesson6PracticeQuestion()"
    >
      Next
    </button>
  `;
}
}
function nextLesson6PracticeQuestion() {
  lesson6PracticeAudio.pause();
  lesson6PracticeAudio.currentTime = 0;

  currentPracticeQuestionIndex++;

  if (
    currentPracticeQuestionIndex >=
    currentPracticeQuestions.length
  ) {
    showLesson6PracticeResult();
    return;
  }

  showLesson6PracticeQuestion();
}
